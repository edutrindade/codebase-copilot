package com.codebasecopilot.shared.error;

import org.springframework.http.HttpStatus;

public enum ErrorCode {
    VALIDATION_FAILED(HttpStatus.BAD_REQUEST),
    MALFORMED_REQUEST(HttpStatus.BAD_REQUEST),
    RESOURCE_NOT_FOUND(HttpStatus.NOT_FOUND),
    METHOD_NOT_ALLOWED(HttpStatus.METHOD_NOT_ALLOWED),
    UNSUPPORTED_MEDIA_TYPE(HttpStatus.UNSUPPORTED_MEDIA_TYPE),
    INTERNAL_ERROR(HttpStatus.INTERNAL_SERVER_ERROR),
    WORKSPACE_NOT_FOUND(HttpStatus.NOT_FOUND),
    WORKSPACE_NOT_EMPTY(HttpStatus.CONFLICT),
    PROJECT_NOT_FOUND(HttpStatus.NOT_FOUND),
    LOCAL_ROOTS_NOT_CONFIGURED(HttpStatus.CONFLICT),
    ROOT_NOT_FOUND(HttpStatus.NOT_FOUND),
    PATH_OUTSIDE_ROOT(HttpStatus.BAD_REQUEST),
    PROJECT_ALREADY_EXISTS(HttpStatus.CONFLICT),
    DIRECTORY_NOT_FOUND(HttpStatus.NOT_FOUND),
    DIRECTORY_NOT_READABLE(HttpStatus.CONFLICT),
    PROJECT_BUSY(HttpStatus.CONFLICT),
    PROJECT_SOURCE_MISMATCH(HttpStatus.CONFLICT),
    UPLOAD_TOO_LARGE(HttpStatus.CONTENT_TOO_LARGE),
    IMPORT_NOT_FOUND(HttpStatus.NOT_FOUND),
    SOURCE_ROOT_NOT_CONFIGURED(HttpStatus.CONFLICT),
    SOURCE_DIRECTORY_NOT_FOUND(HttpStatus.CONFLICT),
    SOURCE_IS_SYMLINK(HttpStatus.CONFLICT),
    SOURCE_NOT_READABLE(HttpStatus.CONFLICT),
    SOURCE_NOT_IMPORTED(HttpStatus.CONFLICT),
    INDEX_JOB_NOT_FOUND(HttpStatus.NOT_FOUND),
    SNAPSHOT_NOT_FOUND(HttpStatus.NOT_FOUND),
    SNAPSHOT_NOT_SEARCHABLE(HttpStatus.CONFLICT),
    SNAPSHOT_LEXICAL_MISMATCH(HttpStatus.CONFLICT),
    EMBEDDINGS_NOT_AVAILABLE(HttpStatus.CONFLICT),
    SNAPSHOT_EMBEDDING_MISMATCH(HttpStatus.CONFLICT),
    CONVERSATION_NOT_FOUND(HttpStatus.NOT_FOUND),
    GENERATION_NOT_AVAILABLE(HttpStatus.CONFLICT),
    // Provider failures (D-051): the account or the provider is at fault, not the API client.
    EMBEDDING_PROVIDER_UNAVAILABLE(HttpStatus.BAD_GATEWAY),
    EMBEDDING_PROVIDER_UNAUTHORIZED(HttpStatus.BAD_GATEWAY),
    EMBEDDING_QUOTA_EXCEEDED(HttpStatus.BAD_GATEWAY),
    EMBEDDING_REQUEST_REJECTED(HttpStatus.BAD_GATEWAY),
    EMBEDDING_RATE_LIMITED(HttpStatus.TOO_MANY_REQUESTS);

    private final HttpStatus status;

    ErrorCode(HttpStatus status) {
        this.status = status;
    }

    public HttpStatus status() {
        return status;
    }
}
